"""PDF 직접 파싱 — 57개 파일 일괄 처리 (Claude API 없이 regex/hardcode)"""
import os, re, subprocess, psycopg2, fitz
from dotenv import load_dotenv
load_dotenv()

conn = psycopg2.connect(os.environ["DATABASE_URL"])

def insert(rows):
    if not rows:
        print("  [경고] 행 없음")
        return
    with conn.cursor() as cur:
        for row in rows:
            cols = list(row.keys())
            col_sql = ", ".join(f'"{c}"' for c in cols)
            placeholders = ", ".join(["%s"] * len(cols))
            cur.execute(f'INSERT INTO fgrr_notices ({col_sql}) VALUES ({placeholders})', [row[c] for c in cols])
    conn.commit()
    print(f"  → {len(rows)}개 삽입")

def delete_by_num(num):
    with conn.cursor() as cur:
        cur.execute('DELETE FROM fgrr_notices WHERE "번호" = %s', (num,))
        print(f"  삭제: {cur.rowcount}행")
    conn.commit()

def read_pdf(path):
    doc = fitz.open(path)
    return "\n".join(p.get_text() for p in doc)

def read_pdf_pdftotext(path):
    result = subprocess.run(['pdftotext', path, '-'], capture_output=True)
    return result.stdout.decode('utf-8', errors='replace')

