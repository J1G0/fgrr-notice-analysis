def parse_0514():
    filename = "0514_북부지방산림청고시제2013-8호(산림보호구역 지정해제).pdf"
    delete(filename)
    text = read_pdf(f"data/notices/{filename}")
    meta = dict(번호="0514", 파일명=filename, 지방산림청="북부지방산림청",
                고시번호="2013-8", 유형="해제", 고시날짜="2013-03-04",
                지정유형="산림유전자원보호구역", 유전자원보호구역_여부=True,
                raw_text=text)
    lines = text.splitlines()
    rows = []
    prev_loc = None
    pattern = re.compile(r'^(\d+)$')
    i = 0
    while i < len(lines):
        l = lines[i].strip()
        if not pattern.match(l):
            i += 1
            continue
        연번 = l
        try:
            loc = lines[i+1].strip()
            지번 = lines[i+2].strip()
            지목 = lines[i+3].strip()
            지적 = lines[i+4].strip()
            편입 = lines[i+5].strip()
            모지번 = lines[i+6].strip() if i+6 < len(lines) else None
        except IndexError:
            i += 1
            continue
        if loc == '〃':
            loc = prev_loc
        else:
            prev_loc = loc
        if 지목 == '〃':
            지목 = '임야'
        if 지번 and (지번.startswith('산') or 지번[0].isdigit()):
            rows.append({**meta,
                "연번": 연번, "소재지": loc, "지번": 지번,
                "지목": 지목, "지적": 지적, "해제면적": 편입,
                "비고": 모지번 if 모지번 and 모지번 != '-' else None})
            i += 7
        else:
            i += 1
    insert(rows)

# ── 0066 ─────────────────────────────────────────────────────────
def parse_0066():
    filename = "0066_북부지방산림청고시제2023-28호(산림보호구역 지정해제 고시).pdf"
    delete(filename)
    text = read_pdf(f"data/notices/{filename}")
    meta = dict(번호="0066", 파일명=filename, 지방산림청="북부지방산림청",
                고시번호="2023-28", 유형="해제", 고시날짜="2023-12-12",
                소유자="국(산림청)", raw_text=text)

    # 구역별 분리: 합계\n43필 기준
    idx = text.find("합계\n43필")
    text_su = text[:idx] if idx > 0 else text
    text_yu = text[idx:] if idx > 0 else ""

    # 행 패턴: 연번 시도 시군 읍면 리동 [지번] 지목 지적 지정면적 해제면적
    pattern = re.compile(
        r'(\d+)\s+(강원|경기)\s+(\S+)\s+(\S+)\s+'
        r'(\S+)\s+(?:(\S+)\s+)?'
        r'(임야|전|답|도로|묘지|잡종지|구거|대)\s+'
        r'([\d,]+)\s+([\d,]+)\s+([\d,]+)',
        re.DOTALL
    )

    def split_리동_지번(f5, f6):
        if f6:
            return f5, f6
        m = re.match(r'^(.*?)(산\d+[\-\d]*)$', f5)
        if m and m.group(1):
            return m.group(1), m.group(2)
        return f5, None

    rows = []
    for 지정유형, 유전_여부 in [("산림유전자원보호구역", True)]:
        sec = text_yu
        for m in pattern.finditer(sec):
            리동, 지번 = split_리동_지번(m.group(5), m.group(6))
            rows.append({**meta,
                "연번": m.group(1), "시도": m.group(2), "시군": m.group(3),
                "읍면": m.group(4), "리동": 리동,
                "소재지": f"{m.group(2)} {m.group(3)} {m.group(4)} {리동}",
                "지번": 지번, "지목": m.group(7),
                "지적": m.group(8), "지정면적": m.group(9), "해제면적": m.group(10),
                "지정유형": 지정유형, "유전자원보호구역_여부": 유전_여부})
    insert(rows)

