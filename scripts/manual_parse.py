"""파일별 직접 파싱 스크립트"""
import os, re, psycopg2, fitz
from dotenv import load_dotenv
load_dotenv()

conn = psycopg2.connect(os.environ["DATABASE_URL"])

def insert(rows):
    with conn.cursor() as cur:
        for row in rows:
            cols = list(row.keys())
            col_sql = ", ".join(f'"{c}"' for c in cols)
            placeholders = ", ".join(["%s"] * len(cols))
            cur.execute(f'INSERT INTO fgrr_notices ({col_sql}) VALUES ({placeholders})', [row[c] for c in cols])
    conn.commit()
    print(f"  → {len(rows)}개 삽입")

def delete(filename):
    with conn.cursor() as cur:
        cur.execute('DELETE FROM fgrr_notices WHERE "파일명" = %s', (filename,))
        print(f"  삭제: {cur.rowcount}행")
    conn.commit()

def read_pdf(path):
    doc = fitz.open(path)
    return "\n".join(p.get_text() for p in doc)

